"""Turn the raw THRUPUT lines into the table and the figure data of the paper. Every value is the
mean over the repetitions of one (format, context) cell with its relative stdev; ratios are
normalized to BF16 from the same cell set. Run: python parse.py (reads results/raw_g*.txt, falls back
to the shipped logs_subset/serving/r5_all.txt so it reproduces without a GPU); --tex out.tex also
writes the pgfplots figure.
"""
from __future__ import annotations

import argparse, glob, os, re, statistics as st

NAMES = [("bf16", "BF16"), ("mxint8_wkv", "MXINT8"), ("mxfp8w_wkv", "MXFP8"),
         ("mxfp6w_wkv", "MXFP6"), ("ssnf_wkv", "SSNF")]
CTX = [2048, 4096, 8192, 16384]

def load(pattern: str) -> dict[tuple[str, int], list[float]]:
    """Collect tok/s samples per (config, context) cell from raw log files matching pattern."""
    runs, cur = {}, None
    for path in sorted(glob.glob(pattern)):
        for line in open(path):
            if line.startswith("###"):
                m = re.search(r"cfg=(\S+) ctx=(\d+)", line)
                cur = (m.group(1), int(m.group(2))) if m else None
            m = re.search(r"tok_s=([\d.]+)", line)
            if m and cur:
                runs.setdefault(cur, []).append(float(m.group(1)))
    return runs

def main() -> None:
    """Print the throughput table and BF16-normalized ratios; optionally write the pgfplots figure."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "results", "raw_g*.txt"))
    ap.add_argument("--tex")
    a = ap.parse_args()
    runs = load(a.raw)
    if not runs and a.raw == ap.get_default("raw"):
        shipped = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                               "..", "..", "logs_subset", "serving", "r5_all.txt")
        runs = load(shipped)
    if not runs:
        raise SystemExit(f"no results found in {a.raw} -- run run.sh first")

    print(f"{'format':8}" + "".join(f"{c//1024}K".rjust(18) for c in CTX) + "   (mean tok/s, rel.std, n)")
    worst = 0.0
    for key, label in NAMES:
        cells = []
        for c in CTX:
            v = runs.get((key, c), [])
            if not v:
                cells.append("—".rjust(18)); continue
            m = st.mean(v); s = st.stdev(v) if len(v) > 1 else 0.0
            worst = max(worst, 100 * s / m)
            cells.append(f"{m:8.1f} ({100*s/m:4.2f}%,n{len(v)})")
        print(f"{label:8}" + "".join(cells))

    print(f"\nlargest relative standard deviation: {worst:.2f}%")
    print("\nnormalized to BF16")
    ratios = {}
    for key, label in NAMES:
        r = []
        for c in CTX:
            v, b = runs.get((key, c), []), runs.get(("bf16", c), [])
            r.append(st.mean(v) / st.mean(b) if v and b else float("nan"))
        ratios[key] = r
        print(f"  {label:8}" + "  ".join(f"{x:6.3f}" for x in r))
    ss = ratios["ssnf_wkv"]
    print(f"\nSSNF over BF16: {min(ss):.2f}--{max(ss):.2f}x")
    for key, label in NAMES[1:-1]:
        cr = [s / b for s, b in zip(ss, ratios[key])]
        print(f"SSNF over {label}: {min(cr):.2f}--{max(cr):.2f}x")

    if a.tex:
        fills = ["ssnfA", "ssnfB", "ssnfC", "ssnfD", "ssnfE"]
        body = []
        for (key, _), fill in zip(NAMES, fills):
            pts = " ".join(f"({c//1024}K,{v:.3f})" for c, v in zip(CTX, ratios[key]))
            body.append(f"      \\addplot[fill={fill}, draw=black, line width=0.4pt]\n"
                        f"        coordinates {{{pts}}};")
        open(a.tex, "w").write(
            "% generated by experiments/serving-throughput/parse.py\n"
            "\\begin{tikzpicture}\n  \\begin{axis}[ybar, bar width=6pt,\n"
            "      symbolic x coords={2K,4K,8K,16K}, xtick=data, ymin=0,\n"
            "      ylabel={Normalized Throughput}, xlabel={Input Sequence Length},\n"
            "      legend style={at={(0.5,1.02)}, anchor=south, legend columns=5, font=\\scriptsize}]\n"
            + "\n".join(body) + "\n      \\legend{BF16,MXINT8,MXFP8,MXFP6,SSNF}\n"
            "  \\end{axis}\n\\end{tikzpicture}\n")
        print(f"\nwrote {a.tex}")

if __name__ == "__main__":
    main()
